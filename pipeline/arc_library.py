def _parse_num(raw):
    """Parse view/share/save counts: '12.5k', '1,2M', '45.000', '15000' → float|None."""
    if raw is None:
        return None
    if isinstance(raw, (int, float)):
        return float(raw)
    s = str(raw).strip().lower()
    if not s or s in ("-", "–", "—", "n/a"):
        return None
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*([km])\b", s)
    if m:
        num = float(m.group(1).replace(",", "."))
        return num * (1_000_000 if m.group(2) == "m" else 1_000)
    # Remove thousands separators like 45.000 or 45,000
    s_clean = re.sub(r"(?<=\d)[.,](?=\d{3}\b)", "", s)
    m2 = re.search(r"\d+(?:[.,]\d+)?", s_clean)
    return float(m2.group(0).replace(",", ".")) if m2 else None


def _parse_pct(raw):
    """Parse completion/retention percent: '32%', '32,5%', '0.325' → percentage (0..100) or None."""
    if raw is None:
        return None
    if isinstance(raw, (int, float)):
        return float(raw) * 100.0 if 0 < float(raw) <= 1.0 else float(raw)
    s = str(raw).strip()
    if not s or s in ("-", "–", "—", "n/a"):
        return None
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*%", s)
    if m:
        return float(m.group(1).replace(",", "."))
    v = _parse_num(s)
    if v is None:
        return None
    return v * 100.0 if 0 < v <= 1.0 else v


def _norm_header(h):
    h = h.lower().strip()
    if "views 7" in h or "view 7" in h: return "views_7d"
    if "views 24" in h or "view 24" in h: return "views_24h"
    if "view" in h or "lượt xem" in h: return "views"
    if "xem hết" in h or "completion" in h: return "completion_pct"
    if "giữ chân" in h or "retention" in h: return "retention_3s"
    if "share" in h or "chia sẻ" in h: return "shares"
    if "save" in h or "lưu" in h: return "saves"
    if h == "arc" or "mã arc" in h: return "arc"
    if "clip" in h: return "clip"
    if "link" in h: return "url"
    if "ngày" in h: return "date"
    return h


def read_published(published_dir=None):
    """Read published clip metrics from content/published/ (Markdown tables + optional *.json)."""
    pdir = Path(published_dir or PUBLISHED)
    if not pdir.exists():
        return []
    records = []
    for f in sorted(pdir.glob("*.md")):
        lines = f.read_text(encoding="utf-8").splitlines()
        headers = None
        for ln in lines:
            if not ln.startswith("|"):
                headers = None
                continue
            cells = [c.strip() for c in ln.strip("|").split("|")]
            if re.match(r"^\|[-\s|:]+\|$", ln):
                continue
            if headers is None:
                headers = [_norm_header(c) for c in cells]
                continue
            row = {headers[i]: (cells[i] if i < len(cells) else "") for i in range(len(headers))}
            arc_m = re.search(r"\b(ARC-\d{3}|ONEUP-CORE-ARC)\b", row.get("arc", ""), re.I)
            if not arc_m:
                continue
            views_7d = _parse_num(row.get("views_7d"))
            views_24h = _parse_num(row.get("views_24h"))
            views = views_7d if views_7d is not None else (views_24h if views_24h is not None else _parse_num(row.get("views")))
            records.append({
                "source_file": f.name,
                "clip": row.get("clip") or row.get("url") or "",
                "arc": arc_m.group(1).upper(),
                "views": views,
                "views_24h": views_24h,
                "views_7d": views_7d,
                "retention_3s": _parse_pct(row.get("retention_3s")),
                "completion_pct": _parse_pct(row.get("completion_pct")),
                "shares": _parse_num(row.get("shares")),
                "saves": _parse_num(row.get("saves")),
            })
    for f in sorted(pdir.glob("*.json")):
        try:
            doc = json.loads(f.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        items = doc if isinstance(doc, list) else doc.get("clips") or doc.get("items") or [doc]
        for it in items:
            if not isinstance(it, dict):
                continue
            arc_m = re.search(r"\b(ARC-\d{3}|ONEUP-CORE-ARC)\b", str(it.get("arc") or ""), re.I)
            if not arc_m:
                continue
            views = _parse_num(it.get("views_7d") if it.get("views_7d") is not None else it.get("views") if it.get("views") is not None else it.get("views_24h"))
            records.append({
                "source_file": f.name,
                "clip": it.get("clip") or it.get("id") or "",
                "arc": arc_m.group(1).upper(),
                "views": views,
                "views_24h": _parse_num(it.get("views_24h")),
                "views_7d": _parse_num(it.get("views_7d")),
                "retention_3s": _parse_pct(it.get("retention_3s")),
                "completion_pct": _parse_pct(it.get("completion_pct")),
                "shares": _parse_num(it.get("shares")),
                "saves": _parse_num(it.get("saves")),
            })
    return records


def is_win(rec, median_views=None, median_completion=None, min_views=DEFAULT_MIN_VIEWS,
           min_completion=DEFAULT_MIN_COMPLETION, min_save_share_rate=DEFAULT_MIN_SAVE_SHARE_RATE):
    """Decide whether one published clip counts as a win. Empty metrics never count as a win."""
    views = rec.get("views")
    comp = rec.get("completion_pct")
    saves = rec.get("saves") or 0.0
    shares = rec.get("shares") or 0.0
    if views is None and comp is None:
        return False
    # Beat target thresholds or beat channel median (when ≥2 clips establish a median)
    view_target = max(min_views, median_views) if median_views is not None else min_views
    comp_target = max(min_completion, median_completion) if median_completion is not None else min_completion
    if views is not None and views >= view_target:
        return True
    if comp is not None and comp >= comp_target:
        return True
    if views and views > 0 and (saves + shares) / views >= min_save_share_rate and views >= min_views * 0.5:
        return True
    return False


def sync_published(published_dir=None, path=None, patterns=None, min_views=DEFAULT_MIN_VIEWS,
                   min_completion=DEFAULT_MIN_COMPLETION, dry_run=False):
    """Sync actual published performance from content/published/ into ARC uses/wins/win_rate and patterns.md."""
    records = read_published(published_dir)
    lib = load(path)
    all_views = [r["views"] for r in records if r.get("views") is not None]
    all_comps = [r["completion_pct"] for r in records if r.get("completion_pct") is not None]
    med_v = float(statistics.median(all_views)) if len(all_views) >= 2 else None
    med_c = float(statistics.median(all_comps)) if len(all_comps) >= 2 else None

    by_arc = {}
    for r in records:
        w = is_win(r, median_views=med_v, median_completion=med_c, min_views=min_views, min_completion=min_completion)
        st = by_arc.setdefault(r["arc"], {"uses": 0, "wins": 0, "clips": []})
        st["uses"] += 1
        st["wins"] += 1 if w else 0
        st["clips"].append({"clip": r["clip"], "views": r["views"], "completion_pct": r["completion_pct"], "win": w})

    updated = []
    for a in lib["arcs"]:
        aid = a["id"]
        if aid in by_arc:
            a["uses"] = by_arc[aid]["uses"]
            a["wins"] = by_arc[aid]["wins"]
            a["win_rate"] = _compute_win_rate(a["uses"], a["wins"])
            updated.append({"id": aid, "uses": a["uses"], "wins": a["wins"], "win_rate": a["win_rate"]})
        else:
            a["win_rate"] = _compute_win_rate(a.get("uses", 0), a.get("wins", 0))

    if not dry_run:
        save(lib, path)
        pat_p = Path(patterns or PATTERNS)
        if pat_p.exists():
            render_patterns(path, pat_p)

    return {"records": len(records), "median_views": med_v, "median_completion": med_c, "updated": updated}


def _rel(target, from_file):
    return Path(os.path.relpath(ROOT / target, Path(from_file).resolve().parent)).as_posix()


def _cell(s):
    return str(s if s is not None else "").replace("|", "/").replace("\n", " ").strip()


def _replace_block(text, begin, end, body, heading):
    block = f"{begin}\n{body.rstrip()}\n{end}"
    if begin in text and end in text:
        return text[: text.index(begin)] + block + text[text.index(end) + len(end):]
    return text.rstrip("\n") + f"\n\n{heading}\n{block}\n"


def render_patterns(path=None, patterns=None):
    lib = load(path); p = Path(patterns or PATTERNS)
    L = ["Khung xương tái dùng (Khối 5 của teardown). `[...]` là chỗ thay nội dung chủ đề mới. Bằng chứng = clip đối thủ đạt chuẩn outlier đã teardown; `seen` = số bằng chứng; `win_rate` = `wins/uses` cập nhật tự động qua `python3 pipeline/arc_library.py sync-published`. Gate 0 ưu tiên ARC có `win_rate` cao nhất (`pipeline/scripts/gate0.py`).", "",
         "| id | tên | khung xương | beat (vai trò · giây · chức năng giữ chân) | cơ chế hook | seen | uses | wins | win_rate | bằng chứng |", "|---|---|---|---|---|---|---|---|---|---|"]
    for a in lib["arcs"]:
        sk = "<br>".join(f"{i}. {_cell(x)}" for i, x in enumerate(a.get("skeleton", []), 1))
        bt = "<br>".join(f"{_cell(b.get('role'))} · {_cell(b.get('seconds'))}s" + (f" · ~{b['syllables'][0]}–{b['syllables'][1]} âm tiết" if b.get("syllables") else "") + f" · {_cell(b.get('function'))}" for b in a.get("beats", [])) or "chưa có (teardown cũ, chạy lại để có beat)"
        ev = "<br>".join(f"{_cell(e.get('creator') or e.get('source'))}" + (f" {e['ratio']}x" if e.get("ratio") else "") +
                         (f" ([teardown]({_rel(e['teardown'], p)}))" if e.get("teardown") else "") for e in a.get("evidence", []))
        wr = f"{a['win_rate']:.0%}" if a.get("win_rate") is not None else "—"
        L.append(f"| {a['id']} | {_cell(a.get('name'))} | {sk} | {bt} | {_cell(a.get('hook_mechanism'))} | {a['seen']} | {a.get('uses', 0)} | {a.get('wins', 0)} | {wr} | {ev} |")
    t = p.read_text(encoding="utf-8")
    p.write_text(_replace_block(t, ARC_BEGIN, ARC_END, "\n".join(L), "## Story arcs (ARC-NNN)"), encoding="utf-8")


def render_ideas(path=None, ideas=None):
    lib = load(path); p = Path(ideas or IDEAS)
    L = ["| Ý tưởng | ARC | Kênh | Độ dài | Hook nháp | Teardown nguồn | Thêm | Trạng thái |", "|---|---|---|---|---|---|---|---|"]
    for x in lib["ideas"]:
        L.append(f"| {_cell(x['idea'])} | {x['arc']} | {CHANNELS[x['channel']]} | {_cell(x.get('length_s'))}s | {_cell(x.get('hook'))} | "
                 f"[{Path(x['teardown']).stem}]({_rel(x['teardown'], p)}) | {x['date']} | {x['status']} |")
    t = p.read_text(encoding="utf-8")
    p.write_text(_replace_block(t, IDEA_BEGIN, IDEA_END, "\n".join(L), "## Từ teardown (ARC)"), encoding="utf-8")


def get(arc_id, path=None):
    return next((a for a in load(path)["arcs"] if a["id"] == arc_id), None)


def best_arc(arcs, format_filter=None):
    """Pick the top ARC prioritizing highest win_rate, then wins, then evidence seen, then fewest uses.

    When `format_filter` is provided (e.g. 'story_metaphor'), excludes ARCs explicitly tagged with a
    different `format_compatibility` (such as 'instructional_list') so listicle ARCs never pollute story channels.
    """
    if not arcs:
        return None
    pool = arcs
    if format_filter:
        compat = [a for a in arcs if a.get("format_compatibility", "any") in ("any", format_filter)]
        if compat:
            pool = compat
    def key(a):
        wr = a.get("win_rate")
        if wr is None:
            wr = _compute_win_rate(a.get("uses", 0), a.get("wins", 0))
        return (wr if wr is not None else -1.0, a.get("wins", 0), a.get("seen", 0), -a.get("uses", 0))
    return max(pool, key=key)


def main():
    a = sys.argv[1:]
    if not a or a[0] in ("-h", "--help"):
        print(__doc__)
        return 0 if a else 2
    def opt(n, d=None):
        return a[a.index(n) + 1] if n in a else d
    cmd = a[0]
    if cmd == "sync-published":
        res = sync_published(
            published_dir=opt("--published-dir"),
            path=opt("--index"),
            patterns=opt("--patterns"),
            min_views=float(opt("--min-views", str(DEFAULT_MIN_VIEWS))),
            min_completion=float(opt("--min-completion", str(DEFAULT_MIN_COMPLETION))),
            dry_run="--dry-run" in a,
        )
        print(f"sync-published: {res['records']} published clip(s) with ARC · updated {len(res['updated'])} ARC(s)"
              + (" (dry-run)" if "--dry-run" in a else ""))
        for u in res["updated"]:
            wr = f"{u['win_rate']:.0%}" if u["win_rate"] is not None else "—"
            print(f"  {u['id']}: uses={u['uses']} wins={u['wins']} win_rate={wr}")
        return 0
    if cmd == "render":
        render_patterns(opt("--index"), opt("--patterns"))
        if IDEAS.exists():
            render_ideas(opt("--index"))
        print("rendered ARC tables")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
