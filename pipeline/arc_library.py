#!/usr/bin/env python3
"""Story-arc library ARC-NNN (Viral DNA, Khối 5 of templates/clip-teardown.md). Stdlib only.

Source of truth: research/blueprints/index.json {"arcs": [...]} (machine). Human view: the generated table between
ARC:BEGIN / ARC:END in research/trends/patterns.md. Adaptation ideas (Khối 6) go to the generated table between
ARC-IDEAS:BEGIN / ARC-IDEAS:END in content/idea-bank.md. Both views are rebuilt from the JSON on every upsert, so editing
them by hand is lost — edit index.json (uses/wins, names) instead.

  arc = upsert_arc(arc_block, evidence)        # same skeleton (similarity ≥ 0.6) → add evidence; else new ARC-NNN
  push_ideas(arc_id, angles, teardown_path)    # Khối 6 → idea-bank rows (dedupe per teardown + channel)
  sync_published(published_dir=...)            # feedback loop: read content/published/ → update uses/wins/win_rate
  render_patterns() / render_ideas()           # rewrite the generated sections

CLI:
  python3 pipeline/arc_library.py sync-published [--published-dir content/published] [--min-views 10000] [--min-completion 30] [--dry-run]
  python3 pipeline/arc_library.py render

Evidence is keyed by source URL/file, so re-running a teardown never double counts: seen = len(evidence).
"""
import difflib, json, os, re, statistics, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "research/blueprints/index.json"
PATTERNS = ROOT / "research/trends/patterns.md"
IDEAS = ROOT / "content/idea-bank.md"
PUBLISHED = ROOT / "content/published"
THRESHOLD = 0.6
ROLES = ("hook", "dẫn dắt", "câu hỏi", "chứng minh", "lật kèo", "giải thích", "áp dụng", "kết")
ARC_BEGIN = "<!-- ARC:BEGIN (generated by pipeline/arc_library.py from research/blueprints/index.json — do not edit here) -->"
ARC_END = "<!-- ARC:END -->"
IDEA_BEGIN = "<!-- ARC-IDEAS:BEGIN (generated by pipeline/arc_library.py — Khối 6 of each teardown; status lives in research/blueprints/index.json) -->"
IDEA_END = "<!-- ARC-IDEAS:END -->"
CHANNELS = {"hi_oneup": "@hi.oneup", "vanhiep_tech": "@vanhiep.tech"}
DEFAULT_MIN_VIEWS = 10000
DEFAULT_MIN_COMPLETION = 30.0  # percent
DEFAULT_MIN_SAVE_SHARE_RATE = 0.02


def _compute_win_rate(uses, wins):
    if not uses or uses <= 0:
        return None
    return round(wins / uses, 3)


def load(path=None):
    p = Path(path or LIB)
    lib = json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}
    lib.setdefault("arcs", []); lib.setdefault("ideas", [])
    if lib.get("modes"):  # migrate the old script-mode list (SMnn) once
        for m in lib.pop("modes"):
            u, w = m.get("uses", 0), m.get("wins", 0)
            lib["arcs"].append({"id": f"ARC-{len(lib['arcs']) + 1:03d}", "legacy_id": m["id"], "name": "", "skeleton": m["formula"],
                                "beats": [], "hook_mechanism": "", "uses": u, "wins": w, "win_rate": _compute_win_rate(u, w),
                                "evidence": [{"source": s} for s in m.get("sources", [])]})
    for a in lib["arcs"]:
        a["seen"] = len(a.get("evidence", []))
        a["win_rate"] = _compute_win_rate(a.get("uses", 0), a.get("wins", 0))
    return lib


def save(lib, path=None):
    p = Path(path or LIB); p.parent.mkdir(parents=True, exist_ok=True)
    for a in lib["arcs"]:
        a["seen"] = len(a.get("evidence", []))
        a["win_rate"] = _compute_win_rate(a.get("uses", 0), a.get("wins", 0))
    p.write_text(json.dumps(lib, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


def _norm(s):
    return re.sub(r"\[[^\]]*\]", " ", (s or "").lower())


def similarity(a, b):
    """0..1. Beat-role sequence (when both have roles) and skeleton text, equal weight."""
    ta = " ".join(_norm(x) for x in a.get("skeleton", [])); tb = " ".join(_norm(x) for x in b.get("skeleton", []))
    text = difflib.SequenceMatcher(None, ta, tb).ratio()
    ra = [x.get("role") for x in a.get("beats", []) if x.get("role")]; rb = [x.get("role") for x in b.get("beats", []) if x.get("role")]
    if ra and rb: return round(0.5 * difflib.SequenceMatcher(None, ra, rb).ratio() + 0.5 * text, 3)
    return round(text, 3)


def upsert_arc(arc, evidence, path=None, threshold=THRESHOLD):
    """arc = {"name", "skeleton": [...], "beats": [{role, function, seconds, transition}], "hook_mechanism"};
    evidence = {"source", "creator", "ratio", "views", "followers", "date", "teardown"}. Returns (arc_id, is_new)."""
    if not arc or not arc.get("skeleton"): return None, False
    lib = load(path)
    same_src = next((x for x in lib["arcs"] if any(e.get("source") == evidence.get("source") for e in x.get("evidence", []))), None)
    best = max(lib["arcs"], key=lambda x: similarity(x, arc), default=None)
    if same_src:  # re-teardown of a clip already in the library: refresh that arc, never fork a duplicate
        tgt, new = same_src, False
        if any("[" in s for s in arc["skeleton"]) or not any("[" in s for s in tgt.get("skeleton", [])):
            tgt["skeleton"] = arc["skeleton"]
            for k in ("beats", "hook_mechanism", "name"):
                if arc.get(k): tgt[k] = arc[k]
    elif best and similarity(best, arc) >= threshold:
        tgt, new = best, False
        if not tgt.get("beats") and arc.get("beats"): tgt["beats"] = arc["beats"]
        if not tgt.get("hook_mechanism") and arc.get("hook_mechanism"): tgt["hook_mechanism"] = arc["hook_mechanism"]
        if not tgt.get("name") and arc.get("name"): tgt["name"] = arc["name"]
    else:
        n = max([int(m.group(1)) for x in lib["arcs"] if (m := re.fullmatch(r"ARC-(\d+)", x["id"]))] or [0]) + 1
        tgt = {"id": f"ARC-{n:03d}", "name": arc.get("name", ""), "skeleton": arc["skeleton"], "beats": arc.get("beats", []),
               "hook_mechanism": arc.get("hook_mechanism", ""), "uses": 0, "wins": 0, "win_rate": None, "evidence": []}
        lib["arcs"].append(tgt); new = True
    ev = {k: v for k, v in evidence.items() if v not in (None, "")}
    old = next((e for e in tgt["evidence"] if e.get("source") == ev.get("source")), None)
    if old: old.update(ev)
    else: tgt["evidence"].append(ev)
    save(lib, path)
    return tgt["id"], new


def push_ideas(arc_id, angles, teardown, date, path=None):
    """Khối 6 angles {"hi_oneup": {"idea", "hook", "length_s"}, "vanhiep_tech": {...}} → lib["ideas"] (dedupe teardown+channel)."""
    lib = load(path); added = 0
    for ch, a in (angles or {}).items():
        if ch not in CHANNELS or not a or not a.get("idea"): continue
        row = next((x for x in lib["ideas"] if x["teardown"] == teardown and x["channel"] == ch), None)
        data = {"arc": arc_id, "channel": ch, "idea": a["idea"], "hook": a.get("hook", ""), "length_s": a.get("length_s"),
                "teardown": teardown, "date": date}
        if row: row.update({k: v for k, v in data.items() if k != "date"})
        else: lib["ideas"].append(dict(data, status="ý tưởng")); added += 1
    save(lib, path)
    return added


